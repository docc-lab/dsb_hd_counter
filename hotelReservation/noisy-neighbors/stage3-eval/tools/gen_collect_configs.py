#!/usr/bin/env python3
"""gen_collect_configs.py -- predictor-training collection sweep for the stage-3 testbed.

Writes configs/collect/<name>.yaml (one per point) and configs/collect/plan.txt
(`<aggressor pool> <yaml>` per line, in run order) for run-collect.sh.

Design (2026-10-23, node-4 booted with SMT ON for this sweep):
  * every point differs from the nine phased eval configs (victim 3600 / SN
    5200-5400 / SS 6100-6300 / int extras 3600-4800) so the predictor is not
    evaluated on its own training points;
  * contention reaches processing_time only through SMT siblings, so the
    aggressor pool is the victim's sibling threads 76,78 (cpu4<->76, cpu6<->78),
    with a few points on 4,6,76,78 (siblings + run-queue sharing);
  * baselines (no aggressors) at every victim rate used, for the labeler's
    baseline_stats; they run first;
  * bursty object shapes give several contention onsets per run.
All runs use the 140 s phased layout with ARM=none (mitigation never fires),
so p2 and p3 are one 120 s contention window.
"""
import os
import sys

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "configs", "collect")
SIB = "76,78"          # siblings of the victim's cores
SIB_OWN = "4,6,76,78"  # siblings + the victim's own cores

SN_AGGR = [("socialNetwork", "compose-post"), ("socialNetwork", "post-storage"),
           ("socialNetwork", "social-graph"), ("socialNetwork", "user-timeline")]
SS_AGGR = [("sockshop", "cart"), ("sockshop", "catalogue"), ("sockshop", "order")]


def lg(rps, shape, off=None, extra=None):
    """loadgen block as YAML lines. shape: 'fixed'|'exp' or dict(burst)."""
    if isinstance(shape, dict):
        sh = ("{burst_s: %d, idle_s: %d, peak_rps: %d, base_rps: %d}"
              % (shape["burst_s"], shape["idle_s"], shape["peak_rps"], shape["base_rps"]))
    else:
        sh = shape
    parts = ["rps: %d" % rps, "shape: %s" % sh]
    if off is not None:
        parts.append("start_offset_s: %d" % off)
    if extra is not None:
        parts.append("extra: {rps: %d, shape: %s, start_offset_s: %d}" % extra)
    return "{" + ", ".join(parts) + "}"


def burst(burst_s, idle_s, peak, base):
    return {"burst_s": burst_s, "idle_s": idle_s, "peak_rps": peak, "base_rps": base}


def config(name, note, hr, sn=None, ss=None, aggr=(), replicas=2):
    tb = ["  hotelReservation:", "    loadgen: %s" % hr]
    if sn is not None:
        tb += ["  socialNetwork:", "    loadgen: %s" % sn, "    replicas: %d" % replicas]
    if ss is not None:
        tb += ["  sockshop:", "    loadgen: %s" % ss, "    replicas: %d" % replicas]
    ag = ["aggressors: []"] if not aggr else ["aggressors:"] + [
        "  - {testbed: %s, service: %s, role: bad}" % a for a in aggr]
    return "\n".join([
        "# predictor collection point -- %s" % note,
        "# generated by tools/gen_collect_configs.py; run via run-collect.sh (ARM=none)",
        "experiment:",
        "  name: %s" % name,
        "  duration_s: 140",
        "  warmup_s: 30",
        "  cooldown_s: 30",
        "  runs: 1",
        "  target_node: node-4",
        "testbeds:", *tb,
        "victim:",
        "  testbed: hotelReservation",
        "  service: search",
        "  image: docclabgroup/search-online:v2.3.0",
        '  cpu_set: "4,6"',
        "  score_log: true",
        *ag, ""])


BOTH = tuple(SN_AGGR + SS_AGGR)
V = 3200  # victim operating rate for ext points (eval used 3600)
MID_B = (burst(15, 25, 5000, 800), burst(15, 25, 6000, 1000))

# (name, pool, note, kwargs). Order = run order: baselines and mid points
# first so a truncated sweep is still usable.
PLAN = [
    ("col-base-3200", SIB, "baseline, victim 3200 exp, no aggressors",
     dict(hr=lg(3200, "exp"))),
    ("col-ext-mid-steady", SIB, "ext mid steady: SN 3500 / SS 4200 fixed @20s",
     dict(hr=lg(V, "exp"), sn=lg(3500, "fixed", 20), ss=lg(4200, "fixed", 20), aggr=BOTH)),
    ("col-ext-mid-bursty", SIB, "ext mid bursty: 15s bursts / 25s idle, peak 5000/6000",
     dict(hr=lg(V, "exp"), sn=lg(5000, MID_B[0], 20), ss=lg(6000, MID_B[1], 20), aggr=BOTH)),
    ("col-int-2000-off20", SIB, "int: victim 800 + 2000 exp @20s (total 2800), co-tenants idle",
     dict(hr=lg(800, "exp", extra=(2000, "exp", 20)), sn=lg(0, "fixed"), ss=lg(0, "fixed"), aggr=BOTH)),
    ("col-ext-heavy-steady", SIB, "ext heavy steady: SN 7000 / SS 8000 fixed @20s",
     dict(hr=lg(V, "exp"), sn=lg(7000, "fixed", 20), ss=lg(8000, "fixed", 20), aggr=BOTH)),
    ("col-base-1500", SIB, "baseline, victim 1500 exp",
     dict(hr=lg(1500, "exp"))),
    ("col-ext-sn-only", SIB, "ext SN only: SN 4500 exp @20s, sockshop absent",
     dict(hr=lg(V, "exp"), sn=lg(4500, "exp", 20), aggr=tuple(SN_AGGR))),
    ("col-ext-ss-only", SIB, "ext SS only: SS 5000 exp @20s, socialNetwork absent",
     dict(hr=lg(V, "exp"), ss=lg(5000, "exp", 20), aggr=tuple(SS_AGGR))),
    ("col-int-4200-off20", SIB, "int: victim 800 + 4200 fixed @20s (total 5000, past the knee)",
     dict(hr=lg(800, "exp", extra=(4200, "fixed", 20)), sn=lg(0, "fixed"), ss=lg(0, "fixed"), aggr=BOTH)),
    ("col-ext-light-steady", SIB, "ext light steady: SN 2000 / SS 2500 fixed @20s",
     dict(hr=lg(V, "exp"), sn=lg(2000, "fixed", 20), ss=lg(2500, "fixed", 20), aggr=BOTH)),
    ("col-ext-light-bursty", SIB, "ext light bursty: 15s/25s, peak 3000/3600, base 500/600",
     dict(hr=lg(V, "exp"), sn=lg(3000, burst(15, 25, 3000, 500), 20),
          ss=lg(3600, burst(15, 25, 3600, 600), 20), aggr=BOTH)),
    ("col-mixed-mid", SIB, "mixed: ext mid fixed @20s + int extra 2400 exp @50s on victim 800",
     dict(hr=lg(800, "exp", extra=(2400, "exp", 50)), sn=lg(3500, "fixed", 20),
          ss=lg(4200, "fixed", 20), aggr=BOTH)),
    ("col-ext-heavy-bursty", SIB, "ext heavy bursty: 10s/20s, peak 8000/9000, base 1000/1200",
     dict(hr=lg(V, "exp"), sn=lg(8000, burst(10, 20, 8000, 1000), 20),
          ss=lg(9000, burst(10, 20, 9000, 1200), 20), aggr=BOTH)),
    ("col-base-4000", SIB, "baseline, victim 4000 exp",
     dict(hr=lg(4000, "exp"))),
    ("col-ext-mid-steady-pool4", SIB_OWN, "ext mid steady, pool = siblings + victim cores",
     dict(hr=lg(V, "exp"), sn=lg(3500, "fixed", 20), ss=lg(4200, "fixed", 20), aggr=BOTH)),
    ("col-ext-mid-exp", SIB, "ext mid Poisson: SN 3500 / SS 4200 exp @20s",
     dict(hr=lg(V, "exp"), sn=lg(3500, "exp", 20), ss=lg(4200, "exp", 20), aggr=BOTH)),
    ("col-int-3000-off40", SIB, "int: victim 800 + 3000 exp @40s (total 3800)",
     dict(hr=lg(800, "exp", extra=(3000, "exp", 40)), sn=lg(0, "fixed"), ss=lg(0, "fixed"), aggr=BOTH)),
    ("col-ext-heavy-rep3", SIB, "ext heavy exp, SN/SS replicas 3",
     dict(hr=lg(V, "exp"), sn=lg(7000, "exp", 20), ss=lg(8000, "exp", 20), aggr=BOTH, replicas=3)),
    ("col-ext-mid-v1500", SIB, "ext mid steady with a lightly loaded victim (1500)",
     dict(hr=lg(1500, "exp"), sn=lg(3500, "fixed", 20), ss=lg(4200, "fixed", 20), aggr=BOTH)),
    ("col-mixed-bursty", SIB, "mixed: ext mid bursty @20s + int extra 1500 exp @60s on victim 3200",
     dict(hr=lg(V, "exp", extra=(1500, "exp", 60)), sn=lg(5000, MID_B[0], 20),
          ss=lg(6000, MID_B[1], 20), aggr=BOTH)),
    ("col-ext-heavy-steady-pool4", SIB_OWN, "ext heavy steady, pool = siblings + victim cores",
     dict(hr=lg(V, "exp"), sn=lg(7000, "fixed", 20), ss=lg(8000, "fixed", 20), aggr=BOTH)),
    ("col-int-bursty-victim", SIB, "int: victim load itself bursty 20s/30s, peak 4500 / base 1000",
     dict(hr=lg(4500, burst(20, 30, 4500, 1000)), sn=lg(0, "fixed"), ss=lg(0, "fixed"), aggr=BOTH)),
    ("col-base-2500", SIB, "baseline, victim 2500 exp",
     dict(hr=lg(2500, "exp"))),
    ("col-ext-mid-v4000", SIB, "ext mid steady with a near-knee victim (4000)",
     dict(hr=lg(4000, "exp"), sn=lg(3500, "fixed", 20), ss=lg(4200, "fixed", 20), aggr=BOTH)),
    ("col-ext-heavy-bursty-pool4", SIB_OWN, "ext heavy bursty, pool = siblings + victim cores",
     dict(hr=lg(V, "exp"), sn=lg(8000, burst(10, 20, 8000, 1000), 20),
          ss=lg(9000, burst(10, 20, 9000, 1200), 20), aggr=BOTH)),
]


def main():
    os.makedirs(OUT, exist_ok=True)
    names = [p[0] for p in PLAN]
    assert len(names) == len(set(names)), "duplicate config names"
    plan_lines = []
    for name, pool, note, kw in PLAN:
        path = os.path.join(OUT, name + ".yaml")
        with open(path, "w", newline="\n") as f:
            f.write(config(name, note, **kw))
        plan_lines.append("%s configs/collect/%s.yaml" % (pool, name))
    with open(os.path.join(OUT, "plan.txt"), "w", newline="\n") as f:
        f.write("# <AGGR_CPUSET> <config>  -- run order for run-collect.sh\n")
        f.write("\n".join(plan_lines) + "\n")
    print("wrote %d configs + plan.txt to %s" % (len(PLAN), os.path.relpath(OUT)))
    print("estimated wall time at ~5.5 min/run: %.1f h" % (len(PLAN) * 5.5 / 60))


if __name__ == "__main__":
    sys.exit(main())
